"""Extract ASCII 32-95 from the ROM font source into a ca65 data file."""
import re, sys
src, out = sys.argv[1], sys.argv[2]
vals = [int(m.group(1), 2) for m in re.finditer(r'^\s*db\s+%([01]{8})', open(src).read(), re.M)]
glyphs = vals[32 * 8:96 * 8]
with open(out, 'w') as f:
    f.write('; HUD font: ASCII 32-95, 8 bytes per char (generated by tools/mkfont.py from the ROM font)\n')
    f.write('.export _hudfont\n.segment "RODATA"\n_hudfont:\n')
    for i in range(0, len(glyphs), 8):
        f.write('    .byte ' + ','.join('$%02x' % b for b in glyphs[i:i + 8]) + '  ; %r\n' % chr(32 + i // 8))
print(len(vals) // 8, 'chars in source,', len(glyphs) // 8, 'written')
