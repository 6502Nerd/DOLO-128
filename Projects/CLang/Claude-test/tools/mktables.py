"""Generate tables.s: sine table and quarter-square multiply tables."""
import math
sin = [round(127 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
sq = [n * n // 4 for n in range(512)]

def emit(f, name, vals):
    f.write('_%s:\n' % name)
    for i in range(0, len(vals), 16):
        f.write('    .byte ' + ','.join(str(v & 0xff) for v in vals[i:i + 16]) + '\n')

with open('tables.s', 'w') as f:
    f.write('; Generated by tools/mktables.py - do not edit\n')
    f.write('.export _sintab, _sq_lo, _sq_hi\n.segment "RODATA"\n')
    emit(f, 'sintab', sin)
    f.write('; quarter squares n*n/4 for n = 0..511 (math.s multiplies)\n')
    emit(f, 'sq_lo', [v & 0xff for v in sq])
    emit(f, 'sq_hi', [v >> 8 for v in sq])
